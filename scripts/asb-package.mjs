const MARKER = `# Generated by ASB installer: ${ASB_APP_ID}`;
export const DEBIAN_DEPENDS = 'nodejs (>= 20), sqlite3, python3, python3-gi, gir1.2-gtk-4.0 (>= 4.10), gir1.2-adw-1 (>= 1.4), xdg-utils';
// Keep this list explicit. A source checkout can contain private local files.
