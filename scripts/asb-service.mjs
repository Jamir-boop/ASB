import { execFile } from 'node:child_process';
import { constants } from 'node:fs';
import { access, mkdir, readFile as readFileAsync, readdir as readdirAsync, rm, stat } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { findRunningService, readServiceRuntime } from './asb-instance.mjs';
import { runEngine, shouldStartTray, startEngine, stopRunning } from './asb-engine.mjs';
import { contents, replace, safeParents } from './asb-package.mjs';
export { readServiceRuntime, findRunningService } from './asb-instance.mjs';

const execFileAsync = promisify(execFile);
const sessionUnitName = 'asb-session.service';
export const unitMarker = '# Generated by ASB: asb.service';
export const sessionUnitMarker = `# Generated by ASB: ${sessionUnitName}`;
export const autostartMarker = '# Generated by ASB: engine autostart';
const configHome = (env) => env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config');
export const unitPath = (env = process.env) => path.join(configHome(env), 'systemd', 'user', 'asb.service');
export const sessionUnitPath = (env = process.env) => path.join(path.dirname(unitPath(env)), sessionUnitName);
export const autostartPath = (env = process.env) => path.join(configHome(env), 'autostart', 'asb-engine.desktop');
const defaultLauncher = fileURLToPath(new URL('./asb', import.meta.url));
function executablePath(value, name) {
  if (typeof value !== 'string' || !path.isAbsolute(value) || /[\s\x00-\x1f\x7f-\x9f%$\\'"]/.test(value)) {
    throw new Error(`${name} must be absolute and contain no whitespace, control characters, quotes, %, $, or backslashes.`);
  }
  return value;
}

async function executable(file) {
  try { return (await stat(file)).isFile() && (await access(file, constants.X_OK), true); }
  catch (error) { if (['ENOENT', 'EACCES'].includes(error.code)) return false; throw error; }
}

// The Node and launcher paths of the unit and of the autostart entry: one rule for both.
async function enginePaths({ nodeExecutable = process.execPath, launcherExecutable = process.env.ASB_INSTALLED_LAUNCHER } = {}) {
  const node = executablePath(nodeExecutable, 'The Node executable path');
  if (!await executable(node)) throw new Error('The Node executable must be an executable file.');
  let launcher = defaultLauncher;
  if (launcherExecutable && path.isAbsolute(launcherExecutable)) {
    executablePath(launcherExecutable, 'The launcher path');
    if (await executable(launcherExecutable)) launcher = launcherExecutable;
  }
  executablePath(launcher, 'The launcher path');
  if (!await executable(launcher)) throw new Error('The ASB launcher must be an executable file.');
  return { node, launcher };
}

const unitText = ({ node, launcher }) => `${unitMarker}\n[Unit]\nDescription=ASB (Agent Switch Board) server\nAfter=graphical-session.target\nConditionFileIsExecutable=${launcher}\nStartLimitIntervalSec=60\nStartLimitBurst=5\n\n[Service]\nType=simple\nEnvironment=ASB_NODE=${node}\nExecStart=${launcher} service run\nRestart=on-failure\nRestartSec=5\n# Apps that ASB opens must survive a service stop or restart.\nKillMode=process\n\n[Install]\nWantedBy=graphical-session.target\n`;
export const serviceUnit = async (options) => unitText(await enginePaths(options));
const sessionUnitText = ({ node, launcher }) => `${sessionUnitMarker}
[Unit]
Description=ASB engine check at the start of a desktop session
PartOf=graphical-session.target
After=graphical-session.target asb.service
ConditionFileIsExecutable=${launcher}

[Service]
Type=oneshot
RemainAfterExit=yes
Environment=ASB_NODE=${node}
ExecStart=${launcher} service session-start

[Install]
WantedBy=graphical-session.target
`;

// The XDG autostart entry (plan Appendix E). Without ASB_NODE, the launcher sees only the desktop PATH at login.
// TryExec skips the entry after an uninstall removed the launcher.
const entryText = ({ node, launcher }) => `[Desktop Entry]\n${autostartMarker}\nType=Application\nTryExec=${launcher}\nName=ASB engine\nComment=Starts the ASB engine for the phone and your other machines\nExec=env ASB_NODE=${node} ${launcher} engine start\nIcon=local.asb.AgentSwitchBoard\nTerminal=false\nNoDisplay=true\nX-GNOME-Autostart-enabled=true\n`;
export const autostartEntry = async (options) => entryText(await enginePaths(options));

// Plan L6: the systemd user unit when a user manager answers and the graphical session target is active,
// else XDG autostart in a desktop session, else none.
export async function autostartMode({ env = process.env, execFile = execFileAsync } = {}) {
  try {
    await execFile('systemctl', ['--user', 'show-environment']);
    let state = '';
    try { state = (await execFile('systemctl', ['--user', 'is-active', 'graphical-session.target'])).stdout; }
    catch (error) { state = error.stdout; }
    if (String(state ?? '').trim() === 'active') return 'systemd';
  } catch {}
  return env.XDG_CURRENT_DESKTOP || env.DESKTOP_SESSION ? 'xdg' : 'none';
}

function parseEnvironment(text, separator) {
  const env = Object.create(null);
  for (const line of text.split(separator)) {
    const equals = line.indexOf('=');
    if (equals > 0) env[line.slice(0, equals)] = line.slice(equals + 1);
  }
  return env;
}

export function sessionRestartReason({ managerEnv, engineEnv, trayWanted, trayRunning }) {
  for (const key of ['DISPLAY', 'WAYLAND_DISPLAY', 'XAUTHORITY']) {
    if ((managerEnv[key] ?? '') !== (engineEnv[key] ?? '')) return `${key} changed`;
  }
  return trayWanted && !trayRunning ? 'tray not running' : '';
}

async function hasTray(proc, readFile, readdir) {
  try {
    let running = false;
    for (const tid of await readdir(`${proc}/task`)) {
      const children = await readFile(`${proc}/task/${tid}/children`, 'utf8');
      for (const pid of children.trim().split(/\s+/).filter(Boolean)) {
        if ((await readFile(`/proc/${pid}/cmdline`, 'utf8')).includes('asb-tray.py')) running = true;
      }
    }
    return running;
  } catch { return false; }
}

async function sessionStart({ execFile, log, readFile, readdir }) {
  try {
    const mainPid = String((await execFile('systemctl', ['--user', 'show', '-p', 'MainPID', '--value', 'asb.service'])).stdout ?? '').trim();
    const pid = Number(mainPid);
    if (!/^\d+$/.test(mainPid) || !Number.isSafeInteger(pid) || pid <= 0) return 0;
    const { stdout } = await execFile('systemctl', ['--user', 'show-environment']);
    // Leave systemd's shell quoting in place. It cannot be used as a plain display value.
    const managerEnv = parseEnvironment(String(stdout ?? ''), '\n');
    const proc = `/proc/${pid}`;
    let engineEnv = {};
    try { engineEnv = parseEnvironment(await readFile(`${proc}/environ`, 'utf8'), '\0'); } catch {}
    const trayWanted = shouldStartTray(managerEnv, 'linux');
    const trayRunning = trayWanted && await hasTray(proc, readFile, readdir);
    const reason = sessionRestartReason({ managerEnv, engineEnv, trayWanted, trayRunning });
    if (reason) {
      log(`ASB restarts its engine for the new desktop session: ${reason}.`);
      await execFile('systemctl', ['--user', 'try-restart', 'asb.service']);
    }
    return 0;
  } catch (error) {
    log(`ASB service: ${error.message.split(/\r?\n/, 1)[0]}`);
    return 1;
  }
}

// The bytes of an ASB file, or null when it is missing. A file without the ASB marker is not changed.
async function managedFile(file, marker, kind) {
  await safeParents(file);
  const bytes = await contents(file);
  if (bytes && !bytes.toString('utf8').split('\n').includes(marker)) throw new Error(`ASB kept an unrelated ${kind} file: ${file}`);
  return bytes;
}
const managedUnit = (file, marker = unitMarker) => managedFile(file, marker, 'service');
const managedEntry = (file) => managedFile(file, autostartMarker, 'autostart');

// With keepOnFailure, a failed disable keeps the unit and logs the message.
async function removeUnit(file, previous, execFile, log, keepOnFailure = false) {
  const name = path.basename(file);
  try { await execFile('systemctl', ['--user', 'disable', '--now', name]); }
  catch (error) { if (!keepOnFailure) throw error; log(`ASB kept ${file}: systemctl --user disable failed.`); return; }
  if (!(await contents(file))?.equals(previous)) throw new Error('ASB kept a service file that changed during uninstall.');
  await rm(file);
  await execFile('systemctl', ['--user', 'daemon-reload']);
  log(name === sessionUnitName ? 'ASB session service is removed.' : 'ASB user service is removed.');
}

async function removeEntry(file, previous, log) {
  if (!(await contents(file))?.equals(previous)) throw new Error('ASB kept an autostart file that changed during this command.');
  await rm(file);
  log('ASB XDG autostart entry is removed.');
}

export async function main(args, { env = process.env, execFile = execFileAsync, platform = process.platform, log = console.log,
  start = startEngine, stop = stopRunning, find = findRunningService, readFile = readFileAsync, readdir = readdirAsync } = {}) {
  if (platform !== 'linux') throw new Error('The ASB user service requires Linux.');
  if (args.length !== 1 || !['run', 'install', 'uninstall', 'status', 'session-start'].includes(args[0])) {
    console.error('Usage: asb service run|install|uninstall|status|session-start');
    return 2;
  }
  if (args[0] === 'run') { await runEngine({ env, platform, execFile }); return 0; }
  if (args[0] === 'session-start') return sessionStart({ execFile, log, readFile, readdir });
  if (args[0] === 'status') {
    const mode = await autostartMode({ env, execFile });
    if (mode === 'systemd') {
      let code = 0;
      try { log((await execFile('systemctl', ['--user', 'is-active', 'asb.service'])).stdout.trim()); }
      catch (error) { log(error.stdout?.trim() || 'unknown'); code = Number.isInteger(error.code) ? error.code : 1; }
      log(`Runtime file: ${await readServiceRuntime(env) ? 'valid' : 'missing or invalid'}.`);
      return code;
    }
    if (mode === 'xdg') log(`XDG autostart entry: ${await managedEntry(autostartPath(env)).catch(() => null) ? autostartPath(env) : 'not installed'}`);
    else log('No desktop session was found.');
    // As systemctl is-active does: 0 when the engine runs, else 3.
    const running = await find(env);
    log(`Engine: ${running ? 'running' : 'not running'}`);
    return running ? 0 : 3;
  }
  const unitFile = unitPath(env);
  const sessionFile = sessionUnitPath(env);
  const entryFile = autostartPath(env);
  if (!path.isAbsolute(unitFile)) throw new Error('XDG_CONFIG_HOME must be an absolute folder.');
  if (args[0] === 'uninstall') {
    const unit = await managedUnit(unitFile);
    const session = await managedUnit(sessionFile, sessionUnitMarker);
    const entry = await managedEntry(entryFile);
    if (session) await removeUnit(sessionFile, session, execFile, log);
    if (unit) await removeUnit(unitFile, unit, execFile, log);
    if (entry) {
      await removeEntry(entryFile, entry, log);
      return stopRunning(await find(env), log);
    }
    if (!unit && !session) log('ASB user service is not installed.');
    return 0;
  }
  // The paths first: a bad Node or launcher path changes no file and runs no systemctl.
  const paths = await enginePaths({ launcherExecutable: env.ASB_INSTALLED_LAUNCHER || '' });
  const { launcher } = paths;
  const mode = await autostartMode({ env, execFile });
  if (mode === 'none') {
    log(`No desktop session was found. Run asb service install from your desktop session, or run ${launcher} engine start after you log in.`);
    return 1;
  }
  if (mode === 'systemd') {
    const unit = await managedUnit(unitFile);
    const session = await managedUnit(sessionFile, sessionUnitMarker);
    const entry = await managedEntry(entryFile).catch(() => null);
    await mkdir(path.dirname(unitFile), { recursive: true, mode: 0o700 });
    await replace(unitFile, Buffer.from(unitText(paths)), unit, 0o644);
    await replace(sessionFile, Buffer.from(sessionUnitText(paths)), session, 0o644);
    if (entry) await removeEntry(entryFile, entry, log);
    // Any running engine stops first (detached, of the entry, or of the unit). Else the unit engine refuses the runtime record and restarts again and again.
    const running = await find(env);
    if (running) await stop(running, log);
    await execFile('systemctl', ['--user', 'daemon-reload']);
    await execFile('systemctl', ['--user', 'enable', '--now', 'asb.service']);
    await execFile('systemctl', ['--user', 'enable', sessionUnitName]);
    log('ASB user service is installed and started.');
  } else {
    const entry = await managedEntry(entryFile);
    // Only marked units of the other mode go. Without a user manager they stay; the runtime record lets only one engine run.
    const unit = await managedUnit(unitFile).catch(() => null);
    const session = await managedUnit(sessionFile, sessionUnitMarker).catch(() => null);
    await mkdir(path.dirname(entryFile), { recursive: true, mode: 0o700 });
    await replace(entryFile, Buffer.from(entryText(paths)), entry, 0o644);
    if (session) await removeUnit(sessionFile, session, execFile, log, true);
    if (unit) await removeUnit(unitFile, unit, execFile, log, true);
    await start({ env, execFile });
    log(`ASB starts at login through XDG autostart. Window managers without XDG autostart must run: ${launcher} engine start`);
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = await main(process.argv.slice(2)); }
  catch (error) { console.error(`ASB service: ${error.message}`); process.exitCode = 1; }
}
