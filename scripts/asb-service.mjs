import { execFile } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { constants } from 'node:fs';
import { access, link, lstat, mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { findRunningService, readServiceRuntime } from './asb-instance.mjs';
import { runEngine, startEngine, stopRunning } from './asb-engine.mjs';
export { readServiceRuntime, findRunningService } from './asb-instance.mjs';

const execFileAsync = promisify(execFile);
export const unitMarker = '# Generated by ASB: asb.service';
export const autostartMarker = '# Generated by ASB: engine autostart';
const configHome = (env) => env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config');
export const unitPath = (env = process.env) => path.join(configHome(env), 'systemd', 'user', 'asb.service');
export const autostartPath = (env = process.env) => path.join(configHome(env), 'autostart', 'asb-engine.desktop');
const defaultLauncher = fileURLToPath(new URL('./asb', import.meta.url));
function executablePath(value, name) {
  if (typeof value !== 'string' || !path.isAbsolute(value) || /[\s\x00-\x1f\x7f-\x9f%$\\'"]/.test(value)) {
    throw new Error(`${name} must be absolute and contain no whitespace, control characters, quotes, %, $, or backslashes.`);
  }
  return value;
}

async function executable(file) {
  try { return (await stat(file)).isFile() && (await access(file, constants.X_OK), true); }
  catch (error) { if (['ENOENT', 'EACCES'].includes(error.code)) return false; throw error; }
}

// The Node and launcher paths of the unit and of the autostart entry: one rule for both.
async function enginePaths({ nodeExecutable = process.execPath, launcherExecutable = process.env.ASB_INSTALLED_LAUNCHER } = {}) {
  const node = executablePath(nodeExecutable, 'The Node executable path');
  if (!await executable(node)) throw new Error('The Node executable must be an executable file.');
  let launcher = defaultLauncher;
  if (launcherExecutable && path.isAbsolute(launcherExecutable)) {
    executablePath(launcherExecutable, 'The launcher path');
    if (await executable(launcherExecutable)) launcher = launcherExecutable;
  }
  executablePath(launcher, 'The launcher path');
  if (!await executable(launcher)) throw new Error('The ASB launcher must be an executable file.');
  return { node, launcher };
}

const unitText = ({ node, launcher }) => `${unitMarker}\n[Unit]\nDescription=ASB (Agent Switch Board) server\nPartOf=graphical-session.target\nAfter=graphical-session.target\nConditionFileIsExecutable=${launcher}\nStartLimitIntervalSec=60\nStartLimitBurst=5\n\n[Service]\nType=simple\nEnvironment=ASB_NODE=${node}\nExecStart=${launcher} service run\nRestart=on-failure\nRestartSec=5\n# Apps that ASB opens must survive a service stop or restart.\nKillMode=process\n\n[Install]\nWantedBy=graphical-session.target\n`;
export const serviceUnit = async (options) => unitText(await enginePaths(options));

// The XDG autostart entry (plan Appendix E). Without ASB_NODE, the launcher sees only the desktop PATH at login.
const entryText = ({ node, launcher }) => `[Desktop Entry]\n${autostartMarker}\nType=Application\nName=ASB engine\nComment=Starts the ASB engine for the phone and your other machines\nExec=env ASB_NODE=${node} ${launcher} engine start\nIcon=local.asb.AgentSwitchBoard\nTerminal=false\nNoDisplay=true\nX-GNOME-Autostart-enabled=true\n`;
export const autostartEntry = async (options) => entryText(await enginePaths(options));

// Plan L6: the systemd user unit when a user manager answers and the graphical session target is active,
// else XDG autostart in a desktop session, else none.
export async function autostartMode({ env = process.env, execFile = execFileAsync } = {}) {
  try {
    await execFile('systemctl', ['--user', 'show-environment']);
    let state = '';
    try { state = (await execFile('systemctl', ['--user', 'is-active', 'graphical-session.target'])).stdout; }
    catch (error) { state = error.stdout; }
    if (String(state ?? '').trim() === 'active') return 'systemd';
  } catch {}
  return env.XDG_CURRENT_DESKTOP || env.DESKTOP_SESSION ? 'xdg' : 'none';
}

async function contents(file) {
  try {
    if (!(await lstat(file)).isFile()) throw new Error(`ASB will not change a linked or non-file path: ${file}`);
    return await readFile(file);
  } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

async function atomicWrite(file, bytes, previous, mode) {
  const temporary = `${file}.${randomBytes(6).toString('hex')}.tmp`;
  try {
    await writeFile(temporary, bytes, { flag: 'wx', mode });
    if (previous === null) await link(temporary, file);
    else {
      if (!(await contents(file))?.equals(previous)) throw new Error(`ASB kept a file that changed during this command: ${file}`);
      await rename(temporary, file);
    }
  } finally { await rm(temporary, { force: true }); }
}

async function realParents(file) {
  for (let parent = path.dirname(file); parent !== path.dirname(parent); parent = path.dirname(parent)) {
    const info = await lstat(parent).catch((error) => { if (error.code !== 'ENOENT') throw error; });
    if (info && !info.isDirectory()) throw new Error(`ASB will not write through a linked or non-directory folder: ${parent}`);
  }
}

// The bytes of an ASB file, or null when it is missing. A file without the ASB marker is not changed.
async function managedFile(file, marker, kind) {
  await realParents(file);
  const bytes = await contents(file);
  if (bytes && !bytes.toString('utf8').split('\n').includes(marker)) throw new Error(`ASB kept an unrelated ${kind} file: ${file}`);
  return bytes;
}
const managedUnit = (file) => managedFile(file, unitMarker, 'service');
const managedEntry = (file) => managedFile(file, autostartMarker, 'autostart');

// With a kept message, a failed disable keeps the unit and logs the message.
async function removeUnit(file, previous, execFile, log, kept) {
  try { await execFile('systemctl', ['--user', 'disable', '--now', 'asb.service']); }
  catch (error) { if (!kept) throw error; log(kept); return; }
  if (!(await contents(file))?.equals(previous)) throw new Error('ASB kept a service file that changed during uninstall.');
  await rm(file);
  await execFile('systemctl', ['--user', 'daemon-reload']);
  log('ASB user service is removed.');
}

async function removeEntry(file, previous, log) {
  if (!(await contents(file))?.equals(previous)) throw new Error('ASB kept an autostart file that changed during this command.');
  await rm(file);
  log('ASB XDG autostart entry is removed.');
}

export async function main(args, { env = process.env, execFile = execFileAsync, platform = process.platform, log = console.log,
  start = startEngine, stop = stopRunning, find = findRunningService } = {}) {
  if (platform !== 'linux') throw new Error('The ASB user service requires Linux.');
  if (args.length !== 1 || !['run', 'install', 'uninstall', 'status'].includes(args[0])) {
    console.error('Usage: asb service run|install|uninstall|status');
    return 2;
  }
  if (args[0] === 'run') { await runEngine({ env, platform, execFile }); return 0; }
  if (args[0] === 'status') {
    const mode = await autostartMode({ env, execFile });
    if (mode === 'systemd') {
      let code = 0;
      try { log((await execFile('systemctl', ['--user', 'is-active', 'asb.service'])).stdout.trim()); }
      catch (error) { log(error.stdout?.trim() || 'unknown'); code = Number.isInteger(error.code) ? error.code : 1; }
      log(`Runtime file: ${await readServiceRuntime(env) ? 'valid' : 'missing or invalid'}.`);
      return code;
    }
    if (mode === 'xdg') log(`XDG autostart entry: ${await managedEntry(autostartPath(env)).catch(() => null) ? autostartPath(env) : 'not installed'}`);
    else log('No desktop session was found.');
    // As systemctl is-active does: 0 when the engine runs, else 3.
    const running = await find(env);
    log(`Engine: ${running ? 'running' : 'not running'}`);
    return running ? 0 : 3;
  }
  const unitFile = unitPath(env);
  const entryFile = autostartPath(env);
  if (!path.isAbsolute(unitFile)) throw new Error('XDG_CONFIG_HOME must be an absolute folder.');
  if (args[0] === 'uninstall') {
    const unit = await managedUnit(unitFile);
    const entry = await managedEntry(entryFile);
    if (unit) await removeUnit(unitFile, unit, execFile, log);
    if (entry) {
      await removeEntry(entryFile, entry, log);
      return stopRunning(await find(env), log);
    }
    if (!unit) log('ASB user service is not installed.');
    return 0;
  }
  // The paths first: a bad Node or launcher path changes no file and runs no systemctl.
  const paths = await enginePaths({ launcherExecutable: env.ASB_INSTALLED_LAUNCHER || '' });
  const { launcher } = paths;
  const mode = await autostartMode({ env, execFile });
  if (mode === 'none') {
    log(`No desktop session was found. Run asb service install from your desktop session, or run ${launcher} engine start after you log in.`);
    return 1;
  }
  const own = mode === 'systemd' ? unitFile : entryFile;
  const previous = mode === 'systemd' ? await managedUnit(own) : await managedEntry(own);
  // The file of the other mode goes after the write, and only when it has the ASB marker; other files stay with no error.
  const other = await (mode === 'systemd' ? managedEntry(entryFile) : managedUnit(unitFile)).catch(() => null);
  await mkdir(path.dirname(own), { recursive: true, mode: 0o700 });
  await atomicWrite(own, Buffer.from(mode === 'systemd' ? unitText(paths) : entryText(paths)), previous, 0o644);
  if (mode === 'systemd') {
    if (other) await removeEntry(entryFile, other, log);
    // Any running engine stops first (detached, of the entry, or of the unit). Else the unit engine refuses the runtime record and restarts again and again.
    const running = await find(env);
    if (running) await stop(running, log);
    await execFile('systemctl', ['--user', 'daemon-reload']);
    await execFile('systemctl', ['--user', 'enable', '--now', 'asb.service']);
    log('ASB user service is installed and started.');
  } else {
    // Without a user manager the unit stays; the runtime record lets only one engine run.
    if (other) await removeUnit(unitFile, other, execFile, log, `ASB kept ${unitFile}: systemctl --user disable failed.`);
    await start({ env, execFile });
    log(`ASB starts at login through XDG autostart. Window managers without XDG autostart must run: ${launcher} engine start`);
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = await main(process.argv.slice(2)); }
  catch (error) { console.error(`ASB service: ${error.message}`); process.exitCode = 1; }
}
