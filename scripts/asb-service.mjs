import { execFile } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { constants, readFileSync } from 'node:fs';
import { access, chmod, link, lstat, mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { createSwitchboardServer, switchboardPort } from '../src/switchboard.mjs';
import { createPhoneGateway } from '../src/phone-gateway.mjs';
import { createSoundPlayer } from '../src/asb-sounds.mjs';

const execFileAsync = promisify(execFile);
const unitMarker = '# Generated by ASB: asb.service';
const defaultLauncher = fileURLToPath(new URL('./asb', import.meta.url));
const runtimePath = (env) => typeof env.XDG_RUNTIME_DIR === 'string' && path.isAbsolute(env.XDG_RUNTIME_DIR)
  ? path.join(env.XDG_RUNTIME_DIR, 'asb', 'service.json') : null;
const validRuntime = (value) => value && typeof value === 'object' && !Array.isArray(value)
  && Object.keys(value).sort().join(',') === 'pid,port,schema,sourceToken' && value.schema === 1
  && Number.isSafeInteger(value.pid) && value.pid > 0 && value.pid <= 2147483647
  && Number.isInteger(value.port) && value.port >= 1 && value.port <= 65535
  && typeof value.sourceToken === 'string' && /^[a-f0-9]{64}$/.test(value.sourceToken);

export async function readServiceRuntime(env = process.env) {
  const file = runtimePath(env);
  if (!file) return null;
  try {
    const directory = await lstat(path.dirname(file));
    const info = await lstat(file);
    if (!directory.isDirectory() || (directory.mode & 0o777) !== 0o700 || !info.isFile()
      || (info.mode & 0o777) !== 0o600 || info.size > 4096
      || (process.getuid && (info.uid !== process.getuid() || directory.uid !== process.getuid()))) return null;
    const value = JSON.parse(await readFile(file, 'utf8'));
    return validRuntime(value) ? value : null;
  } catch { return null; }
}

export async function findRunningService(env = process.env) {
  const runtime = await readServiceRuntime(env);
  if (!runtime) return null;
  return new Promise((resolve) => {
    let request;
    const done = (value) => { clearTimeout(timer); request?.destroy(); resolve(value); };
    const timer = setTimeout(() => done(null), 2000);
    request = http.get({ host: '127.0.0.1', port: runtime.port, path: '/api/service', agent: false,
      headers: { host: `127.0.0.1:${runtime.port}`, 'X-ASB-Source-Token': runtime.sourceToken } }, (response) => {
      if (response.statusCode !== 200) { done(null); return; }
      let body = '';
      response.on('data', (chunk) => { body += chunk; if (body.length > 4096) done(null); });
      response.on('error', () => done(null));
      response.on('end', () => {
        try {
          const value = JSON.parse(body);
          done(value.service === true && value.pid === runtime.pid ? runtime : null);
        } catch { done(null); }
      });
    });
    request.on('error', () => done(null));
  });
}

function executablePath(value, name) {
  if (typeof value !== 'string' || !path.isAbsolute(value) || /[\s\x00-\x1f\x7f-\x9f%$\\'"]/.test(value)) {
    throw new Error(`${name} must be absolute and contain no whitespace, control characters, quotes, %, $, or backslashes.`);
  }
  return value;
}

async function executable(file) {
  try { return (await stat(file)).isFile() && (await access(file, constants.X_OK), true); }
  catch (error) { if (['ENOENT', 'EACCES'].includes(error.code)) return false; throw error; }
}

export async function serviceUnit({ nodeExecutable = process.execPath, launcherExecutable = process.env.ASB_INSTALLED_LAUNCHER } = {}) {
  const node = executablePath(nodeExecutable, 'The Node executable path');
  if (!await executable(node)) throw new Error('The Node executable must be an executable file.');
  let launcher = defaultLauncher;
  if (launcherExecutable && path.isAbsolute(launcherExecutable)) {
    executablePath(launcherExecutable, 'The launcher path');
    if (await executable(launcherExecutable)) launcher = launcherExecutable;
  }
  executablePath(launcher, 'The launcher path');
  if (!await executable(launcher)) throw new Error('The ASB launcher must be an executable file.');
  return `${unitMarker}\n[Unit]\nDescription=ASB (Agent Switch Board) server\nPartOf=graphical-session.target\nAfter=graphical-session.target\n\n[Service]\nType=simple\nEnvironment=ASB_NODE=${node}\nExecStart=${launcher} service run\nRestart=on-failure\nRestartSec=5\n# Apps that ASB opens must survive a service stop or restart.\nKillMode=process\n\n[Install]\nWantedBy=graphical-session.target\n`;
}

async function contents(file) {
  try {
    if (!(await lstat(file)).isFile()) throw new Error(`ASB will not change a linked or non-file path: ${file}`);
    return await readFile(file);
  } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

async function atomicWrite(file, bytes, previous, mode) {
  const temporary = `${file}.${randomBytes(6).toString('hex')}.tmp`;
  try {
    await writeFile(temporary, bytes, { flag: 'wx', mode });
    if (previous === null) await link(temporary, file);
    else {
      if (!(await contents(file))?.equals(previous)) throw new Error(`ASB kept a file that changed during this command: ${file}`);
      await rename(temporary, file);
    }
  } finally { await rm(temporary, { force: true }); }
}

async function managedUnit(file) {
  const bytes = await contents(file);
  if (bytes && !bytes.toString('utf8').split('\n').includes(unitMarker)) throw new Error(`ASB kept an unrelated service file: ${file}`);
  return bytes;
}

async function runService() {
  const file = runtimePath(process.env);
  if (!file || !(await lstat(process.env.XDG_RUNTIME_DIR).catch(() => null))?.isDirectory()) {
    throw new Error('ASB service run needs an absolute, existing XDG_RUNTIME_DIR folder.');
  }
  const directory = path.dirname(file);
  const previousDirectory = await lstat(directory).catch((error) => { if (error.code !== 'ENOENT') throw error; });
  if (previousDirectory && (!previousDirectory.isDirectory() || (process.getuid && previousDirectory.uid !== process.getuid()))) {
    throw new Error('ASB will not use a linked or foreign runtime folder.');
  }
  await mkdir(directory, { recursive: true, mode: 0o700 });
  await chmod(directory, 0o700);
  const previous = await contents(file);
  if (previous) {
    const saved = await readServiceRuntime();
    if (!saved) throw new Error('ASB kept an invalid service.json. Remove it before starting the service.');
    try { process.kill(saved.pid, 0); throw new Error('The ASB service runtime file belongs to a running process.'); }
    catch (error) { if (error.code !== 'ESRCH') throw error; }
  }
  const port = switchboardPort();
  const sourceToken = randomBytes(32).toString('hex');
  const asbVersion = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;
  const gateway = createPhoneGateway({ localPort: port, asbVersion });
  const server = createSwitchboardServer({ sourceToken, phoneGateway: gateway, serviceMode: true, playSound: createSoundPlayer() });
  let stopping = false;
  let cleanup;
  let startup;
  const stop = () => {
    stopping = true;
    return cleanup ||= (async () => {
      await startup.catch(() => {});
      try {
        const current = await readServiceRuntime();
        if (current?.pid === process.pid && current.sourceToken === sourceToken) await rm(file);
      } finally {
        const closed = new Promise((resolve) => server.close(resolve));
        server.closeAllConnections();
        try { await gateway.stop(); } finally { await closed; }
      }
    })();
  };
  const onSignal = () => { stop().catch((error) => { console.error(`Cannot stop ASB service: ${error.message}`); process.exitCode = 1; }); };
  process.once('SIGTERM', onSignal);
  process.once('SIGINT', onSignal);
  startup = (async () => {
    await new Promise((resolve, reject) => { server.once('error', reject); server.listen(port, '127.0.0.1', resolve); });
    if (stopping) return;
    try {
      await gateway.start();
      const status = await gateway.status();
      if (status.error) console.error(`Cannot start ASB phone access: ${status.error}`);
    } catch (error) { console.error(`Cannot start ASB phone access: ${error.message}`); }
    if (stopping) return;
    await atomicWrite(file, Buffer.from(JSON.stringify({ schema: 1, pid: process.pid, port, sourceToken }) + '\n'), previous, 0o600);
    if (!stopping) console.log(`ASB service: http://127.0.0.1:${port}`);
  })();
  try { await startup; }
  catch (error) { await stop(); throw error; }
}

async function main(args) {
  if (process.platform !== 'linux') throw new Error('The ASB user service requires Linux.');
  if (args.length !== 1 || !['run', 'install', 'uninstall', 'status'].includes(args[0])) {
    console.error('Usage: asb service run|install|uninstall|status');
    return 2;
  }
  if (args[0] === 'run') { await runService(); return 0; }
  if (args[0] === 'status') {
    let code = 0;
    try { console.log((await execFileAsync('systemctl', ['--user', 'is-active', 'asb.service'])).stdout.trim()); }
    catch (error) { console.log(error.stdout?.trim() || 'unknown'); code = Number.isInteger(error.code) ? error.code : 1; }
    console.log(`Runtime file: ${await readServiceRuntime() ? 'valid' : 'missing or invalid'}.`);
    return code;
  }
  const file = path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'systemd', 'user', 'asb.service');
  if (!path.isAbsolute(file)) throw new Error('XDG_CONFIG_HOME must be an absolute folder.');
  const unit = args[0] === 'install' ? await serviceUnit() : null;
  for (let parent = path.dirname(file); parent !== path.dirname(parent); parent = path.dirname(parent)) {
    const info = await lstat(parent).catch((error) => { if (error.code !== 'ENOENT') throw error; });
    if (info && !info.isDirectory()) throw new Error(`ASB will not write through a linked or non-directory folder: ${parent}`);
  }
  const previous = await managedUnit(file);
  if (args[0] === 'install') {
    await mkdir(path.dirname(file), { recursive: true, mode: 0o700 });
    await atomicWrite(file, Buffer.from(unit), previous, 0o644);
    await execFileAsync('systemctl', ['--user', 'daemon-reload']);
    await execFileAsync('systemctl', ['--user', 'enable', '--now', 'asb.service']);
    console.log('ASB user service is installed and started.');
  } else if (previous) {
    await execFileAsync('systemctl', ['--user', 'disable', '--now', 'asb.service']);
    if (!(await contents(file))?.equals(previous)) throw new Error('ASB kept a service file that changed during uninstall.');
    await rm(file);
    await execFileAsync('systemctl', ['--user', 'daemon-reload']);
    console.log('ASB user service is removed.');
  } else console.log('ASB user service is not installed.');
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = await main(process.argv.slice(2)); }
  catch (error) { console.error(`ASB service: ${error.message}`); process.exitCode = 1; }
}
